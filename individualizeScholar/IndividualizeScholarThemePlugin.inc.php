	/**
	 * The homepage blocks to render: the blocks chosen in Individualize's
	 * "Homepage Blocks" option, with the categories of the current issue right
	 * above the first block that shows the current issue (at the end when there
	 * is none) and the latest / most read / most downloaded cards at the end.
	 * Only the template variable changes; Individualize's saved option never
	 * holds these blocks, so Individualize alone keeps working.
	 */
	public static function placeBlocks($blocks, $categories, $highlights) {
		$blocks = array_values(array_filter(is_array($blocks) ? $blocks : array(), function ($block) {
			return $block !== IndividualizeScholarThemePlugin::BLOCK_HIGHLIGHTS && $block !== IndividualizeScholarThemePlugin::BLOCK_CATEGORIES;
		}));
		if ($categories) {
			$position = count($blocks);
			foreach ($blocks as $index => $block) {
				if (in_array($block, self::ISSUE_BLOCKS, true)) {
					$position = $index;
					break;
				}
			}
			array_splice($blocks, $position, 0, array(self::BLOCK_CATEGORIES));
		}
		if ($highlights) {
			$blocks[] = self::BLOCK_HIGHLIGHTS;
		}
		return $blocks;
	}

	/** The cards chosen in the "Homepage cards" option: 'categories', 'highlights' */
	protected function homeBlocks() {
		$chosen = $this->getOption('individualizeScholarHomeBlocks');
		return is_array($chosen) ? $chosen : array();
	}

	/**
	 * Choices of the "journal home country" option: every country by its full
	 * name in the interface language. The list is kept for a day per language,
	 * because the theme options are defined on every request.
	 */
	protected function homeCountryChoices() {
		try {
			$locale = class_exists('AppLocale') ? AppLocale::getLocale() : '';
			$cache = new IsFragmentCache($this->cacheDir(), 86400);
			$choices = $cache->remember('v' . self::VERSION . '-country-options-' . $locale, function () {
				$this->loadCountryNames();
				return IsCountryOptions::build($this->countryNames, __('plugins.themes.individualizeScholar.option.homeCountry.none'));
			});
			return is_array($choices) ? $choices : array();
		} catch (\Throwable $e) {
			error_log('individualizeScholar: unable to list the countries: ' . $e->getMessage());
			return array();
		}
	}

	/**
	 * ISO alpha-2 code of the journal's home country, from the theme option;
	 * '' (nothing saved or not a two-letter code) turns the share of foreign
	 * authors off.
	 */
	protected function homeCountry() {
		$code = strtoupper(trim((string) $this->getOption('individualizeScholarHomeCountry')));
		return preg_match('/^[A-Z]{2}$/', $code) ? $code : '';
	}

	/**
	 * Data and template functions for the page being rendered, then one
	 * output filter for the loading hints, the meta description, the script
	 * and the status comment.
	 */
	public function handleDisplay($hookName, $args) {
		$templateMgr = $args[0];
		$template = $args[1];
		if (!is_string($template)) {
			return false;
		}
		if (strpos($template, 'frontend/') !== 0) {
			$this->addBackendTools($templateMgr, $template);
			return false;
		}
		$this->notes = array();
		$this->printed = array();
		if (!$this->parent) {
			$this->note('parent theme: Individualize is not installed or not enabled');
		}

		try {
			$this->registerTemplateFunctions($templateMgr);
			if ($template === 'frontend/pages/issue.tpl' || $template === 'frontend/pages/indexJournal.tpl') {
				$this->sortArticlesByPages($templateMgr);
			}
			if ($template === 'frontend/pages/indexJournal.tpl') {
				$templateMgr->assign('individualizeScholarFold', self::HOME_ARTICLE_LIMIT);
				$chosen = $this->homeBlocks();
				$categories = in_array('categories', $chosen, true) ? $this->buildCategoryCards() : '';
				$highlights = in_array('highlights', $chosen, true) ? $this->buildHomeHighlights() : '';
				$templateMgr->assign(array(
					'individualizeScholarCategories' => $categories,
					'individualizeScholarHighlights' => $highlights,
					// Set by Individualize's own display hook, which runs first
					'homepageBlocks' => self::placeBlocks($templateMgr->getTemplateVars('homepageBlocks'), $categories !== '', $highlights !== ''),
				));
			}
		} catch (\Throwable $e) {
			$this->note('error: ' . get_class($e) . ': ' . substr($e->getMessage(), 0, 160));
		}

		$description = $this->pageDescription($templateMgr, $template);
		$isArchive = $template === 'frontend/pages/issueArchive.tpl';
		$detail = $this->canSeeDebug();
		$scriptUrl = $this->getAssetUrl('js/individualizeScholar.js');
		$templateMgr->registerFilter('output', function ($output) use ($description, $isArchive, $detail, $template, $scriptUrl) {
			// Sidebar blocks and other partial fetches also pass through this filter
			if (stripos($output, '</html>') === false) {
				return $output;
			}
			$steps = array(
				'header logo priority' => function ($o) { return IsPageHints::prioritizeLogo($o); },
				'footer lazy loading' => function ($o) { return IsPageHints::lazyFooter($o); },
				'meta description' => function ($o) use ($description) { return IsMetaDescription::inject($o, $description); },
			);
			if ($isArchive) {
				$steps['archive cover lazy loading'] = function ($o) { return IsPageHints::lazyCovers($o); };
			}
			$status = array();
			foreach ($steps as $name => $step) {
				$changed = $step($output);
				$status[] = $name . ': ' . ($changed !== $output ? 'inserted' : 'no anchor found');
				$output = is_string($changed) ? $changed : $output;
			}
			$output = IndividualizeScholarThemePlugin::addCacheBuster($output, IndividualizeScholarThemePlugin::VERSION);
			$text = 'individualizeScholar ' . IndividualizeScholarThemePlugin::VERSION;
			if ($detail) {
				$text .= ' | ' . $template . ' | ' . implode(' | ', array_merge($this->notes, $this->printedNotes(), $status));
			}
			$tail = ($scriptUrl !== '' ? IndividualizeScholarThemePlugin::scriptTag($scriptUrl, IndividualizeScholarThemePlugin::VERSION) : '')
				. '<!-- ' . str_replace('--', '- -', $text) . ' -->';
			return IndividualizeScholarThemePlugin::beforePageEnd($output, $tail);
		}, 'individualizeScholar');
		return false;
	}

	/** "<feature>: printed N times" for the status comment */
	protected function printedNotes() {
		$lines = array();
		foreach ($this->printed as $feature => $count) {
			$lines[] = $feature . ': printed ' . $count . ' time(s)';
		}
		return $lines;
	}

	/**
	 * Put $html before the last </body> of the page, else (Individualize
	 * closes the page without </body>) before the last </html>.
	 */
	public static function beforePageEnd($output, $html) {
		foreach (array('body', 'html') as $tag) {
			$count = 0;
			$result = preg_replace_callback('/<\/' . $tag . '>(?!.*<\/' . $tag . '>)/is', function ($m) use ($html) {
				return $html . $m[0];
			}, $output, 1, $count);
			if ($count === 1) {
				return $result;
			}
		}
		return $output . $html;
	}

	/**
	 * Template functions called by the overridden templates. A function that
	 * is already registered (by another plugin) is left alone.
	 */
	protected function registerTemplateFunctions($templateMgr) {
		$functions = array(
			'individualize_scholar_actions' => 'smartyArticleActions',
			'individualize_scholar_country' => 'smartyAuthorCountry',
			'individualize_scholar_coverage' => 'smartyIssueCoverage',
			'individualize_scholar_archive_card' => 'smartyArchiveCard',
		);
		foreach ($functions as $name => $method) {
			if (!isset($templateMgr->registered_plugins['function'][$name])) {
				$templateMgr->registerPlugin('function', $name, array($this, $method));
			}
		}
	}

	protected function countPrinted($feature) {
		$this->printed[$feature] = (isset($this->printed[$feature]) ? $this->printed[$feature] : 0) + 1;
	}

	/**
	 * Articles of every section of the issue (issue page and the current
	 * issue of the home page) in order of their first page number.
	 */
	protected function sortArticlesByPages($templateMgr) {
		$sections = $templateMgr->getTemplateVars('publishedSubmissions');
		if (!is_array($sections) || !$sections) {
			return;
		}
		$templateMgr->assign('publishedSubmissions', IsArticleOrder::sortSections($sections, function ($article) {
			$publication = is_object($article) && method_exists($article, 'getCurrentPublication') ? $article->getCurrentPublication() : null;
			return $publication ? $publication->getData('pages') : '';
		}));
		$this->note('article order by pages: sorted');
	}

	/**
	 * {individualize_scholar_actions article=$article publication=$publication
	 *   context=$context hideAbstract=false assign="actions"}
	 *
	 * Action line under the authors of an article in a list: "Show Abstract |
	 * Download PDF | DOI: 10.xxxx/... | Check in Google Scholar". With
	 * `assign`, the variable gets array('html' => ..., 'pdfGalleyId' => id of
	 * the PDF galley used for "Download PDF", 0 when none), so the template
	 * can leave that galley's own button out; without it the HTML is printed.
	 */
	public function smartyArticleActions($params, $smarty) {
		$result = array('html' => '', 'pdfGalleyId' => 0);
		try {
			$article = isset($params['article']) ? $params['article'] : null;
			$publication = isset($params['publication']) && $params['publication'] ? $params['publication'] : ($article ? $article->getCurrentPublication() : null);
			if ($article && $publication) {
				$result = $this->articleActions($article, $publication, isset($params['context']) ? $params['context'] : null, !empty($params['hideAbstract']));
			}
		} catch (\Throwable $e) {
			error_log('individualizeScholar: unable to build the article actions: ' . $e->getMessage());
		}
		if ($result['html'] !== '') {
			$this->countPrinted('article actions');
		}
		if (!empty($params['assign'])) {
			$smarty->assign($params['assign'], $result);
			return '';
		}
		return $result['html'];
	}

	protected function articleActions($article, $publication, $context, $hideAbstract) {
		$request = Application::get()->getRequest();
		if (!$context || !method_exists($context, 'getPath')) {
			$context = $request->getContext();
		}
		if (!$context) {
			return array('html' => '', 'pdfGalleyId' => 0);
		}
		$dispatcher = $request->getDispatcher();
		$title = (string) $publication->getLocalizedFullTitle();
		if ($title === '') {
			$title = (string) $publication->getLocalizedTitle();
		}
		$abstract = '';
		if (!$hideAbstract) {
			$abstract = (string) $publication->getLocalizedData('abstract');
			$abstract = class_exists('PKPString') ? PKPString::stripUnsafeHtml($abstract) : strip_tags($abstract, '<p><br><b><i><em><strong><sub><sup><ul><ol><li>');
		}
		$download = '';
		$pdfGalleyId = 0;
		$galleys = $publication->getData('galleys');
		if (is_array($galleys) || $galleys instanceof Traversable) {
			foreach ($galleys as $galley) {
				if (method_exists($galley, 'isPdfGalley') && $galley->isPdfGalley()) {
					$download = $dispatcher->url($request, ROUTE_PAGE, $context->getPath(), 'article', 'download', array($article->getBestId(), $galley->getBestGalleyId()));
					$pdfGalleyId = (int) $galley->getId();
					break;
				}
			}
		}
		$id = (int) $article->getId();
		$html = IsArticleActions::render(array(
			'title' => $title,
			'abstract' => $abstract,
			'url' => $dispatcher->url($request, ROUTE_PAGE, $context->getPath(), 'article', 'view', array($article->getBestId())),
			'download' => $download,
			'doi' => $this->articleDoi($publication),
			'panel' => 'ms-abstract-' . $id . '-' . (++$this->panelCount),
		), array(
			'show' => __('plugins.themes.individualizeScholar.article.showAbstract'),
			'hide' => __('plugins.themes.individualizeScholar.article.hideAbstract'),
			'download' => __('plugins.themes.individualizeScholar.article.download'),
			'scholar' => __('plugins.themes.individualizeScholar.article.scholar'),
		));
		return array('html' => $html, 'pdfGalleyId' => $html !== '' ? $pdfGalleyId : 0);
	}

	/**
	 * DOI of the publication ("10.xxxx/..."), or '' when it has none.
	 */
	protected function articleDoi($publication) {
		$doi = '';
		if (method_exists($publication, 'getStoredPubId')) {
			$doi = (string) $publication->getStoredPubId('doi');
		}
		if ($doi === '') {
			$stored = $publication->getData('pub-id::doi');
			$doi = is_scalar($stored) ? (string) $stored : '';
		}
		return IsArticleActions::cleanDoi($doi);
	}

	/**
	 * {individualize_scholar_country author=$author assign="country"}
	 *
	 * Localized name of the author's country (the Country field of the author
	 * metadata), '' when it has none. The author data is not changed.
	 */
	public function smartyAuthorCountry($params, $smarty) {
		$name = '';
		try {
			$author = isset($params['author']) ? $params['author'] : null;
			if ($author && method_exists($author, 'getData')) {
				$name = $this->getCountryName($author->getData('country'));
			}
		} catch (\Throwable $e) {
			error_log('individualizeScholar: unable to read the author country: ' . $e->getMessage());
		}
		if ($name !== '') {
			$this->countPrinted('author country');
		}
		if (!empty($params['assign'])) {
			$smarty->assign($params['assign'], $name);
			return '';
		}
		return htmlspecialchars($name, ENT_QUOTES, 'UTF-8');
	}

	/**
	 * {individualize_scholar_coverage issue=$issue}
	 *
	 * The "Issue Coverage" box: articles and pages, authors and countries with
	 * flags, share of foreign authors.
	 */
	public function smartyIssueCoverage($params, $smarty) {
		$issue = isset($params['issue']) ? $params['issue'] : null;
		if (!$issue || !method_exists($issue, 'getId')) {
			return '';
		}
		try {
			$html = (string) $this->cached('coverage-' . (int) $issue->getId() . '-h' . $this->homeCountry(), $issue->getJournalId(), function () use ($issue) {
				return $this->buildIssueCoverageHtml($issue);
			}, $this->contentSignature($issue->getJournalId(), (int) $issue->getId()));
		} catch (\Throwable $e) {
			error_log('individualizeScholar: unable to build issue coverage: ' . $e->getMessage());
			$this->note('issue coverage error: ' . get_class($e) . ': ' . substr($e->getMessage(), 0, 160));
			return '';
		}
		if ($html !== '') {
			$this->countPrinted('issue coverage');
		}
		return $html;
	}

	/**
	 * {individualize_scholar_archive_card issue=$issue}
	 *
	 * The small card of the Archives page: authors (with the share of foreign
	 * authors), countries with flags, articles and pages.
	 */
	public function smartyArchiveCard($params, $smarty) {
		$issue = isset($params['issue']) ? $params['issue'] : null;
		if (!$issue || !method_exists($issue, 'getId')) {
			return '';
		}
		if (function_exists('set_time_limit') && !$this->printed) {
			// a long Archives list on a cold cache can take a while
			@set_time_limit(120);
		}
		try {
			$html = (string) $this->cached('archive-' . (int) $issue->getId() . '-h' . $this->homeCountry(), $issue->getJournalId(), function () use ($issue) {
				return $this->buildArchiveCardHtml($issue);
			}, $this->contentSignature($issue->getJournalId(), (int) $issue->getId()));
		} catch (\Throwable $e) {
			error_log('individualizeScholar: unable to build the card of issue ' . $issue->getId() . ': ' . $e->getMessage());
			return '';
		}
		if ($html !== '') {
			$this->countPrinted('archive card');
		}
		return $html;
	}

	/**
	 * Dimensions citation badge at the top of the "Article details" table of
	 * the article page (just above the DOI row), for articles with a DOI.
	 */
	public function addDimensionsBadge($hookName, $args) {
		try {
			$smarty = $args[1];
			$output =& $args[2];
			$publication = $smarty->getTemplateVars('publication');
			$doi = $publication ? $this->articleDoi($publication) : '';
			if ($doi !== '' && strpos((string) $output, '__dimensions_badge_embed__') === false) {
				$output .= IsDimensionsBadge::render($doi);
				$this->countPrinted('dimensions badge');
			}
		} catch (\Throwable $e) {
			error_log('individualizeScholar: unable to add the Dimensions badge: ' . $e->getMessage());
		}
		return false;
	}

	/**
	 * Back-end pages (not part of the public site): the "Select all" buttons
	 * and file sizes script for signed-in users. Only complete pages get it;
	 * the script itself does nothing on pages without the lists it serves.
	 */
	protected function addBackendTools($templateMgr, $template = '') {
		try {
			if (!class_exists('Validation') || !Validation::isLoggedIn()) {
				return;
			}
			$tag = IsFileSizes::dataTag($this->workflowFileSizes($template))
				. self::adminScriptTag($this->getAssetUrl('js/individualizeScholarAdmin.js'), self::VERSION, array(
				'all' => __('plugins.themes.individualizeScholar.admin.selectAll'),
				'none' => __('plugins.themes.individualizeScholar.admin.clearAll'),
			));
			$templateMgr->registerFilter('output', function ($output) use ($tag) {
				return IndividualizeScholarThemePlugin::injectAdminScript($output, $tag);
			});
		} catch (\Throwable $e) {
			error_log('individualizeScholar: unable to add the back-end script: ' . $e->getMessage());
		}
	}

	/** Back-end pages that list the files of one submission => word their template contains */
	const FILE_SIZE_PAGES = array('workflow' => 'workflow', 'authorDashboard' => 'authorDashboard', 'reviewer' => 'review');

	/**
	 * Sizes of the files of the submission shown on a workflow, author
	 * dashboard or reviewer page (OJS has already checked that the user may
	 * open it). The submission must belong to the current journal; a reviewer
	 * gets only the files of his or her own review. Empty on other pages.
	 *
	 * @return array submission file id => bytes
	 */
	protected function workflowFileSizes($template) {
		if (!is_string($template)) {
			return array();
		}
		try {
			$request = Application::get()->getRequest();
			$page = $request->getRequestedPage();
			if (!isset(self::FILE_SIZE_PAGES[$page]) || stripos($template, self::FILE_SIZE_PAGES[$page]) === false) {
				return array();
			}
			$args = $request->getRequestedArgs();
			$submissionId = isset($args[0]) ? (int) $args[0] : 0;
			$context = $request->getContext();
			$user = $request->getUser();
			if ($submissionId < 1 || !$context || !$user) {
				return array();
			}
			$pdo = \Illuminate\Database\Capsule\Manager::connection()->getPdo();
			$paths = $page === 'reviewer'
				? IsFileSizes::reviewerPaths($pdo, $submissionId, $context->getId(), $user->getId())
				: IsFileSizes::paths($pdo, $submissionId, $context->getId());
			return IsFileSizes::sizes($paths, Config::getVar('files', 'files_dir'));
		} catch (\Throwable $e) {
			error_log('individualizeScholar: unable to read the file sizes: ' . $e->getMessage());
			return array();
		}
	}

