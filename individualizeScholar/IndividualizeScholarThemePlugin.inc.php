	public function init() {
		$this->setParent(self::PARENT);
		if (!$this->parent) {
			error_log('individualizeScholar: the Individualize theme (plugins/themes/individualizeTheme) is not installed or not enabled');
		}

		$countryOptions = $this->homeCountryChoices();
		$homeCountry = array(
			'label' => __('plugins.themes.individualizeScholar.option.homeCountry.label'),
			'description' => __('plugins.themes.individualizeScholar.option.homeCountry.description'),
			'default' => '',
		);
		if ($countryOptions) {
			$homeCountry['options'] = $countryOptions;
			$this->addOption('individualizeScholarHomeCountry', 'FieldSelect', $homeCountry);
		} else {
			// No country list available: a two-letter code typed by hand still works
			$this->addOption('individualizeScholarHomeCountry', 'FieldText', $homeCountry);
		}
		$this->addOption('individualizeScholarHomeBlocks', 'FieldOptions', array(
			'type' => 'checkbox',
			'label' => __('plugins.themes.individualizeScholar.option.homeBlocks.label'),
			'description' => __('plugins.themes.individualizeScholar.option.homeBlocks.description'),
			'options' => array(
				array('value' => 'categories', 'label' => __('plugins.themes.individualizeScholar.option.homeBlocks.categories')),
				array('value' => 'highlights', 'label' => __('plugins.themes.individualizeScholar.option.homeBlocks.highlights')),
			),
			'default' => array('categories', 'highlights'),
		));

		$this->addStyle('individualizeScholar', 'styles/individualizeScholar.css', array('priority' => STYLE_SEQUENCE_LAST));

		// The Appearance form initializes every theme to list its options; only
		// the journal's active theme adds its features
		if ($this->isActive()) {
			HookRegistry::register('TemplateManager::display', array($this, 'handleDisplay'));
			HookRegistry::register('Templates::Article::Details', array($this, 'addDimensionsBadge'));
		}
	}

